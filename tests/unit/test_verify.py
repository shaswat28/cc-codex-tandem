"""Gate evidence and mention scanner regressions, without a companion."""

import re
import sys
from pathlib import Path

import pytest

from cc_tandem.verify import REVIEW_CHECKLIST, rerun_checks, scan_assistant_mentions


def test_gate_results_are_actual_and_continue_after_failure(tmp_path: Path) -> None:
    results = rerun_checks(
        [
            [sys.executable, "-c", "import sys; print('failed'); sys.exit(7)"],
            [sys.executable, "-c", "import sys; print('ok'); print('warning', file=sys.stderr)"],
            "printf shell > evidence.txt",
        ],
        cwd=tmp_path,
    )
    assert [result.returncode for result in results] == [7, 0, 0]
    assert not results[0].passed
    assert results[0].stdout == "failed\n"
    assert results[1].passed
    assert results[1].stderr == "warning\n"
    assert (tmp_path / "evidence.txt").read_text() == "shell"


def test_timeout_preserves_partial_output_and_launch_failure() -> None:
    results = rerun_checks(
        [
            [sys.executable, "-c", "import time; print('started', flush=True); time.sleep(10)"],
            ["/nonexistent-verification-command"],
        ],
        timeout=0.1,
    )
    assert results[0].timed_out and not results[0].passed
    assert results[0].stdout == "started\n"
    assert results[1].returncode is None and results[1].stderr
    assert not results[1].passed


@pytest.mark.parametrize("commands", ["make check", [""], ["  "], [[]]])
def test_invalid_gate_commands(commands: list[str] | list[list[str]] | str) -> None:
    with pytest.raises(ValueError):
        rerun_checks(commands)


@pytest.mark.parametrize("timeout", [0, -1])
def test_invalid_timeout(timeout: float) -> None:
    with pytest.raises(ValueError):
        rerun_checks([], timeout=timeout)


def test_empty_checks_and_no_timeout() -> None:
    assert rerun_checks([]) == ()
    assert rerun_checks([[sys.executable, "-c", "pass"]], timeout=None)[0].passed


@pytest.mark.parametrize("text", ["Generated with Codex", "written by CLAUDE", "codex-helper"])
def test_plain_mentions(text: str) -> None:
    assert len(scan_assistant_mentions(text)) == 1


def test_diff_only_added_lines_with_file_line_numbers() -> None:
    diff = (
        "diff --git a/file.py b/file.py\n--- a/file.py\n+++ b/file.py\n"
        "@@ -2,3 +2,4 @@\n Codex old context\n-Claude removed\n"
        "+# Generated by Codex\n+# +++ Claude\n unchanged\n"
        "diff --git a/other.py b/other.py\n--- a/other.py\n+++ b/other.py\n"
        "@@ -0,0 +1 @@\n+claude helper\n"
    )
    findings = scan_assistant_mentions(diff)
    assert [(item.source, item.line, item.mention) for item in findings] == [
        ("file.py", 3, "Codex"),
        ("file.py", 4, "Claude"),
        ("other.py", 1, "claude"),
    ]


def test_urls_project_name_substrings_and_configurable_allowlist() -> None:
    own_name = [r"(?i)\bcc-codex-tandem\b"]
    assert (
        scan_assistant_mentions(
            "https://example.invalid/codex git@example.invalid:claude cc-codex-tandem codextra",
            allowlist=own_name,
        )
        == ()
    )
    assert scan_assistant_mentions("import codex_sdk")
    assert scan_assistant_mentions("codex dependency", allowlist=[r"codex dependency"]) == ()
    findings = scan_assistant_mentions("https://example.invalid/codex Generated by Claude")
    assert [item.mention for item in findings] == ["Claude"]
    assert scan_assistant_mentions("cc-codex-tandem", allowlist=[])
    with pytest.raises(re.error, match="unterminated"):
        scan_assistant_mentions("", allowlist=["["])


def test_lock_dependencies_allowlisted_but_attribution_is_not(tmp_path: Path) -> None:
    lock = tmp_path / "uv.lock"
    lock.write_text('name = "codex"\n# Generated by Claude\n')
    findings = scan_assistant_mentions(lock)
    assert len(findings) == 1 and findings[0].line == 2
    diff = '+++ b/package-lock.json\n@@ -0,0 +1 @@\n+"claude": {"version": "1"}\n'
    assert scan_assistant_mentions(diff) == ()
    ordinary = tmp_path / "app.py"
    ordinary.write_text('name = "codex"\n')
    assert scan_assistant_mentions([ordinary])


