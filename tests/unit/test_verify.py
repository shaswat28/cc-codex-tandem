def test_product_docs_do_not_hide_attribution(tmp_path: Path) -> None:
    readme = tmp_path / "README.md"
    readme.write_text("# cc-codex-tandem\nClaude plans, Codex builds\nGenerated by Codex\n")
    assert [item.line for item in scan_assistant_mentions(readme)] == [3]
