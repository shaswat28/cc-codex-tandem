def test_metadata_is_scanned_even_with_empty_diff() -> None:
    findings = scan_assistant_mentions(
        "",
        commit_messages=["Change\nCo-Authored-By: Claude", "Generated by Codex"],
        branch_names=["feature/codex-implementation", "cc-codex-tandem"],
        allowlist=[r"(?i)\bcc-codex-tandem\b"],
    )
    assert [(item.source, item.line) for item in findings] == [
        ("commit-message[1]", 2),
        ("commit-message[2]", 1),
        ("branch[1]", 1),
    ]


